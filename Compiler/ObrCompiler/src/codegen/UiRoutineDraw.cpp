void Generator::emitUiRoutineMeter() {
    emit("uimeter:");
    emit("store.64 r7, " + uiCellText(UiLinkMeter));
    emit("load.64 r0, " + uiCellText(UiMeter + 0));
    emit("or r1, r0, r0");
    emit("place r2, 0");
    emit("lt r0, r1, r2");
    emit("jnz r0, uifault");
    emit("load.64 r0, " + uiCellText(UiMeter + 2));
    emit("or r1, r0, r0");
    emit("place r2, 1");
    emit("lt r0, r1, r2");
    emit("jnz r0, uifault");
    emit("load.64 r0, " + uiCellText(UiMeter + 1));
    emit("or r1, r0, r0");
    emit("place r2, 0");
    emit("le r0, r1, r2");
    emit("jz r0, umhi");
    emit("place r0, 0");
    emit("place r1, 1");
    emit("jnz r1, umdone");
    emit("umhi:");
    emit("load.64 r0, " + uiCellText(UiMeter + 1));
    emit("or r1, r0, r0");
    emit("load.64 r0, " + uiCellText(UiMeter + 2));
    emit("or r2, r0, r0");
    emit("ge r0, r1, r2");
    emit("jz r0, ummid");
    emit("load.64 r0, " + uiCellText(UiMeter + 0));
    emit("place r1, 1");
    emit("jnz r1, umdone");
    emit("ummid:");
    emit("load.64 r0, " + uiCellText(UiMeter + 0));
    emit("or r1, r0, r0");
    emit("load.64 r0, " + uiCellText(UiMeter + 1));
    emit("or r2, r0, r0");
    emit("mul r0, r1, r2");
    emit("or r1, r0, r0");
    emit("load.64 r0, " + uiCellText(UiMeter + 2));
    emit("or r2, r0, r0");
    emit("div r0, r1, r2");
    emit("umdone:");
    emit("load.64 r7, " + uiCellText(UiLinkMeter));
    emit("ret");
  }

void Generator::emitUiRoutineBar() {
    auto reject = [&](int slot, int limit) {
      emit("load.64 r0, " + uiCellText(slot));
      emit("or r1, r0, r0");
      emit("place r2, " + std::to_string(limit));
      emit("lt r0, r1, r2");
      emit("jnz r0, uifault");
    };
    auto paint = [&](int widthSlot, int colorSlot) {
      emit("load.64 r0, " + uiCellText(UiBar + 0));
      emit("store.64 r0, " + uiCellText(UiArg + 0));
      emit("load.64 r0, " + uiCellText(UiBar + 1));
      emit("store.64 r0, " + uiCellText(UiArg + 1));
      emit("load.64 r0, " + uiCellText(widthSlot));
      emit("store.64 r0, " + uiCellText(UiArg + 2));
      emit("load.64 r0, " + uiCellText(UiBar + 3));
      emit("store.64 r0, " + uiCellText(UiArg + 3));
      emit("load.64 r0, " + uiCellText(colorSlot));
      emit("store.64 r0, " + uiCellText(UiArg + 4));
      emit("load.64 r0, " + uiCellText(UiBar + 9));
      emit("store.64 r0, " + uiCellText(UiArg + 5));
      emit("place r0, 36");
      emit("store.64 r0, " + uiCellText(UiArg + 6));
      emit("load.64 r0, " + uiCellText(UiBar + 4));
      emit("store.64 r0, " + uiCellText(UiArg + 7));
      emit("call uibox");
    };
    emit("uibar:");
    emit("store.64 r7, " + uiCellText(UiLinkBar));
    reject(UiBar + 2, 0);
    reject(UiBar + 3, 0);
    reject(UiBar + 4, 0);
    emit("load.64 r0, " + uiCellText(UiBar + 2));
    emit("store.64 r0, " + uiCellText(UiMeter + 0));
    emit("load.64 r0, " + uiCellText(UiBar + 5));
    emit("store.64 r0, " + uiCellText(UiMeter + 1));
    emit("load.64 r0, " + uiCellText(UiBar + 6));
    emit("store.64 r0, " + uiCellText(UiMeter + 2));
    emit("call uimeter");
    emit("store.64 r0, " + uiCellText(UiBar + 10));
    paint(UiBar + 2, UiBar + 7);
    emit("load.64 r0, " + uiCellText(UiBar + 10));
    emit("or r1, r0, r0");
    emit("place r2, 0");
    emit("eq r0, r1, r2");
    emit("jnz r0, ubdone");
    paint(UiBar + 10, UiBar + 8);
    emit("ubdone:");
    emit("load.64 r7, " + uiCellText(UiLinkBar));
    emit("ret");
  }


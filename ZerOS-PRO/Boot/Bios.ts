/**
 * @module ZerOS.Boot.Bios
 * @description 固件设置画面的指令文本
 *
 * ---------------------------------------------------------------------------
 * 文件职责
 * ---------------------------------------------------------------------------
 * 指令正文在旁边的 Bios.obr 里。工具链在加载虚拟模块时编好并填入行列表。
 * 这里只把那些行交给 assemble。标号、call、chars 仍由 assemble 展开。
 * 画面列出已经坐上的硬件和能读到的数。不改配置，也不进入内核。
 *
 * 4096 模式：0 等待 F12，1 空闲，2 设置画面。
 * 4160 页号。4224 盒子编号。4288 行的纵坐标。
 * 4352 键盘已完成次数。4416 等待拍数。4480 键盘口，4 表示没有。
 * 4544 页数。4608 核心序号。4672 字符座位。4736 字符字段。4800 字符起点。
 * 4864 键位名。4928 修饰位。5056 内层返回时暂存的外层链接。
 * r0 是返回值，r1 至 r5 是参数和临时，r7 只做 call 链接。
 * 找键盘口时 r0 至 r5 都占着，盒子编号已经写入 4224，所以借用 r6 当口编号。
 */


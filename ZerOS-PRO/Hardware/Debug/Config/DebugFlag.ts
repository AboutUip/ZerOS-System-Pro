export namespace ZerOS {
  export namespace Hardware {
    export namespace Debug {
      /**
       * 宿主调试是否打开。
       * false：不挂全局入口，不接受调试运行。
       * true：页面全局对象上出现只读的 ZerOSDebug。调试运行仍只接受有限的 ZAP 文本，不执行任意脚本。
       * 经函数返回，是为了手改 true 之后调用处的两条路都还在，不会被收成永远关闭。
       */
      function handEditedFlag(on: boolean): boolean {
        return on;
      }

      export const DebugEnabled = handEditedFlag(false);
    }
  }
}

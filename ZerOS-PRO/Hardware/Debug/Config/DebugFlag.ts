/**
 * @module ZerOS.Hardware.Debug.DebugFlag
 * @description 宿主调试开关
 *
 * ---------------------------------------------------------------------------
 * 文件职责
 * ---------------------------------------------------------------------------
 * 只放页面上的当前值。默认关闭。
 * 值从固件来：BIOS 把 0 或 1 写进位地址 8128，主板看见这次写入后告诉页面。
 * 页面再把同一位落进 NAS 的 `/boot/debug`。下次打开页面先读这个文件。
 * 它不是协议字段，也不是手改常量。不要在这里写密钥、口令或可执行字符串。
 * 主板线程和 CPU 线程各自加载这一份模块，改这里它们看不见。
 * 调试运行的消息里带上当前这一位，那两条线程只认消息里的位。
 * 关闭时，全局对象上不挂调试入口，控制台也不为普通失败开口。
 * 控制台只留给显卡自己坏了、错误帧画不出来的那一种情况，那条路径不看这个开关。
 *
 * ---------------------------------------------------------------------------
 * 代码组织（严格优先级，自上而下，禁止打乱）
 * ---------------------------------------------------------------------------
 *   1. 开关
 */

export namespace ZerOS {
  export namespace Hardware {
    export namespace Debug {
      /**
       * 还没有 `/boot/debug`、固件也还没写过时用这一档。
       * 文件已经存在时以文件为准，这里不再把已经打开的开关关回去。
       */
      let enabled = false;

      /** 页面当前是否接受调试入口和调试运行。调用时读，不要在模块加载时抄走。 */
      export function debugEnabled(): boolean {
        return enabled;
      }

      /**
       * 换成固件刚写下的那一档，或页面从 `/boot/debug` 读到的那一档。
       * 只由页面调用。客程序改不了这个函数。
       */
      export function setDebugEnabled(on: boolean): void {
        enabled = on;
      }
    }
  }
}

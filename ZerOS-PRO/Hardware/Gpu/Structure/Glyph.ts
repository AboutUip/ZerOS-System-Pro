      /** 编码不在封闭集合里时返回 null。 */
      export function glyphRow(code: number, row: number): number | null {
        if (!Number.isInteger(code) || code < GlyphCodeMin || code > GlyphCodeMax) {
          return null;
        }
        if (!Number.isInteger(row) || row < 0 || row >= GlyphHeight) {
          return null;
        }
        const glyph = glyphRows[code - GlyphCodeMin];
        if (glyph === undefined) {
          return null;
        }
        const bits = glyph[row];
        if (bits === undefined) {
          return null;
        }
        return bits;
      }

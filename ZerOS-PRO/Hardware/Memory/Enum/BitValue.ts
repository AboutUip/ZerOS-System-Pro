/**
 * @module ZerOS.Hardware.Memory.BitValue
 * @description 颗粒存储槽位取值（BitValue）
 *
 * ---------------------------------------------------------------------------
 * 文件职责
 * ---------------------------------------------------------------------------
 * 单独定义位元（Bit Cell）的规范取值：仅 0 或 1。
 * 八位组（0–255）不是位元。不包含单元类、打包布局或读写方法。
 *
 * ---------------------------------------------------------------------------
 * 代码组织（严格优先级，自上而下，禁止打乱）
 * ---------------------------------------------------------------------------
 *   1. BitValue 类型
 */

export namespace ZerOS {
  export namespace Hardware {
    export namespace Memory {
      /**
       * 位元规范取值（ZMP1 §4.15）：仅 0 或 1。
       * 封闭二值，禁止追加第三值；不是可增长编码表。
       */
      export type BitValue = 0 | 1;
    }
  }
}
